/**
 * public-projection.ts — backfill the PUBLIC KV keys from the STORED private
 * snapshot (2026-10-19 owner decree; Step 3 §2.2 AC-08 + T-15).
 *
 * Reads insights:snapshot, projects it onto the licence-legal subset
 * (data/site-mode-overrides.json via projectSnapshotToPublic — no re-fetch,
 * no re-scoring: the survivors carry every enrichment unchanged) and writes
 * insights:snapshot-public + today's insights:archive-public:v1:<date>.
 *
 * Use when the public keys are missing while a private snapshot exists —
 * the first flip to SITE_MODE=public, or after a KV/Worker recreation —
 * BEFORE (or immediately after) deploying with SITE_MODE=public, so the
 * public serve path never answers "not ready" for a full ingest cycle. The
 * daily insights-ingest run overwrites both keys from then on.
 *
 * Environment:
 *   CLOUDFLARE_API_TOKEN        (required)
 *   CLOUDFLARE_ACCOUNT_ID       (required)
 *   INSIGHTS_KV_NAMESPACE_ID    (required — the RATES namespace)
 *
 * Manual: pnpm --filter @currena/insights public-projection
 */

import { readFileSync } from 'node:fs';
import { z } from 'zod';

import { projectSnapshotToPublic } from '../src/adapters/index';
import { RestInsightsStore } from '../src/store';

function fail(message: string): never {
  console.error(`\n[public-projection] FATAL: ${message}`);
  process.exit(1);
}

const apiToken = process.env.CLOUDFLARE_API_TOKEN;
const accountId = process.env.CLOUDFLARE_ACCOUNT_ID;
const namespaceId = process.env.INSIGHTS_KV_NAMESPACE_ID;
if (!apiToken || !accountId || !namespaceId) {
  fail('missing environment — needs CLOUDFLARE_API_TOKEN, CLOUDFLARE_ACCOUNT_ID and INSIGHTS_KV_NAMESPACE_ID');
}

// The hidden set: generated by the registry generator, shared with the T-15
// build gate and the Worker's serve-time gate. Absent = fail closed.
const repoRoot = new URL('../../../', import.meta.url);
let overridesRaw: unknown;
try {
  overridesRaw = JSON.parse(readFileSync(new URL('data/site-mode-overrides.json', repoRoot), 'utf8'));
} catch {
  fail('data/site-mode-overrides.json is absent/unreadable — the public projection cannot be built safely (run the registry generator)');
}
const overrides = z
  .object({ version: z.number(), hiddenIndicatorIds: z.array(z.string()), hiddenBoards: z.array(z.string()) })
  .parse(overridesRaw);
const hiddenIds: ReadonlySet<string> = new Set(overrides.hiddenIndicatorIds);

const store = new RestInsightsStore({ apiToken, accountId, namespaceId, retryDelaysMs: [] });

const snapshot = await store.getSnapshot();
if (!snapshot) {
  fail('no stored snapshot under insights:snapshot — run the ingest first (the projection is a subset of a real run)');
}

const publicSnapshot = projectSnapshotToPublic(snapshot, hiddenIds);
const hiddenOnPage = snapshot.readings.length - publicSnapshot.readings.length;
console.log(
  `[public-projection] source snapshot ${snapshot.generatedAt}: ${snapshot.readings.length} readings → ` +
    `${publicSnapshot.readings.length} public-ok readings (${hiddenOnPage} hidden), displayMode=public`,
);
console.log(
  `[public-projection] summary — Global: ${publicSnapshot.summary.global.label ?? 'no label'} · Australia: ${publicSnapshot.summary.australia.label ?? 'no label'}`,
);

await store.putPublicSnapshot(publicSnapshot);
console.log('✍ insights:snapshot-public');
const archiveDate = snapshot.generatedAt.slice(0, 10);
if ((await store.getPublicArchive(archiveDate)) === undefined) {
  await store.putPublicArchive(archiveDate, publicSnapshot);
  console.log(`✍ insights:archive-public:v1:${archiveDate}`);
} else {
  console.log(`· insights:archive-public:v1:${archiveDate} already exists — not overwritten`);
}
const { reads, writes } = store.ops;
console.log(`KV ops: ${reads} reads, ${writes} writes — inside the free-tier daily caps.`);
console.log('[public-projection] done — SITE_MODE=public deployments now have a document to serve.');
