/**
 * db/d1-dump.sql generator — seeds the deployed Worker's D1 database from
 * the sandbox archive (db/custom.db), strictly read-only.
 *
 * Fidelity rule: every cell round-trips through SQLite's own quote()
 * inside the database itself, so each INSERT statement carries SQLite's
 * canonical representation of the stored value — no JavaScript
 * re-encoding of numbers, dates or strings anywhere. The dump is ordered
 * by each table's primary key, so regeneration is deterministic.
 *
 * Usage:
 *   bun scripts/d1-dump.ts
 *     → writes db/d1-dump.sql (gitignored)
 *   wrangler d1 execute aurum-desk --local --file=db/d1-dump.sql
 *   wrangler d1 execute aurum-desk --remote --file=db/d1-dump.sql
 *
 * db/custom.db itself is never rebuilt and never written to from here.
 */
import { Database } from "bun:sqlite";

const TABLES = ["DeskDay", "Observation", "SourceSync", "WatchRule"] as const;

const db = new Database("db/custom.db", { readonly: true });

const out: string[] = [
  "-- AURUM desk archive seed",
  "-- Generated by scripts/d1-dump.ts from db/custom.db (read-only snapshot).",
  "-- The desk of record remains db/custom.db in the sandbox repository;",
  "-- D1 receives this one-time seed and continues on its own.",
  "",
  "PRAGMA defer_foreign_keys = true;",
];

let totalRows = 0;

for (const table of TABLES) {
  const create = db
    .query("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?")
    .get(table) as { sql: string };
  out.push("");
  out.push(`-- ${table}`);
  out.push(create.sql.trim().replace(/;+$/, "") + ";");

  const indexes = db
    .query(
      "SELECT name, sql FROM sqlite_master WHERE type = 'index' AND tbl_name = ? AND sql IS NOT NULL ORDER BY name"
    )
    .all(table) as { name: string; sql: string }[];
  for (const ix of indexes) {
    out.push(ix.sql.trim().replace(/;+$/, "") + ";");
  }

  const cols = (
    db.query(`PRAGMA table_info("${table}")`).all() as { name: string }[]
  ).map((c) => `"${c.name}"`);
  const colList = cols.join(", ");
  const quoted = cols.map((c) => `quote(${c})`).join(" || ',' || ");

  const rows = db
    .query(
      `SELECT 'INSERT INTO "${table}" (${colList}) VALUES (' || ${quoted} || ');' AS stmt FROM "${table}" ORDER BY ${cols[0]}`
    )
    .all() as { stmt: string }[];

  for (const r of rows) out.push(r.stmt);
  totalRows += rows.length;
  console.log(`${table}: ${rows.length} rows`);
}

await Bun.write("db/d1-dump.sql", out.join("\n") + "\n");
console.log(`total: ${totalRows} rows → db/d1-dump.sql`);

db.close();
