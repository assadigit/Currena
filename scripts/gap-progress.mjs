#!/usr/bin/env node
/**
 * gap-progress.mjs — gap-closure S1-M3 progress tooling (docs/gap-closure/
 * 00-OPERATING-RULES.md §3 step 7 + S1-foundation-and-trust.md M1.3).
 *
 * Reads docs/gap-closure/PROGRESS.md, counts `- [x]` vs `- [ ]` milestone
 * lines per `### S<n>` session section, and rewrites the Summary table +
 * the last-updated line between the stable markers
 * `<!-- gap-progress:begin -->` … `<!-- gap-progress:end -->`.
 *
 * Deterministic + idempotent: running it twice produces identical bytes
 * (the only date used is today's, stable within a day). Zero dependencies.
 *
 * Usage:
 *   pnpm gap:progress                       # rewrite the real file
 *   node scripts/gap-progress.mjs <file>    # any PROGRESS.md-shaped file
 *   node scripts/gap-progress.mjs --check   # exit 1 if the file is stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DEFAULT_PATH = join(here, '..', 'docs', 'gap-closure', 'PROGRESS.md');

export const BEGIN_MARK = '<!-- gap-progress:begin -->';
export const END_MARK = '<!-- gap-progress:end -->';

/** Fallback themes (used only when a session has no table row yet). */
export const SESSION_THEMES = {
  S1: 'Foundation and trust',
  S2: 'Foreign holdings of US Treasuries (priority feature)',
  S3: 'US credit, liquidity, fiscal and growth nowcast',
  S4: 'Geopolitics, supply chain and energy',
  S5: 'Australia deep-dive and Australian markets',
  S6: 'New Zealand, China and world links, promotion and polish',
};

/**
 * Count the milestones per session section. A milestone line is a
 * column-0 `- [ ]`/`- [x]` whose text starts with `M<digit>`; the indented
 * evidence sub-bullets and the G1…G13 gap-coverage items never match.
 *
 * @param {string} md the whole PROGRESS.md content
 * @returns {{ id: string, title: string, done: number, total: number }[]}
 */
export function parseSessionCounts(md) {
  const sessions = [];
  let current = null;
  for (const line of md.split('\n')) {
    const section = /^### (S\d)\s+(.+?)\s*(?:\(|$)/.exec(line);
    if (section !== null) {
      current = { id: section[1], title: section[2].trim(), done: 0, total: 0 };
      sessions.push(current);
      continue;
    }
    if (/^#{1,3}\s/.test(line)) {
      current = null; // any other heading ends the section
      continue;
    }
    if (current === null) continue;
    const item = /^- \[( |x)\] M\d+\.\d+/.exec(line);
    if (item !== null) {
      current.total += 1;
      if (item[1] === 'x') current.done += 1;
    }
  }
  return sessions;
}

/** Read the Session→Theme pairs out of an existing summary table (if any). */
export function parseExistingThemes(md) {
  const themes = {};
  const between = md.slice(md.indexOf(BEGIN_MARK) + BEGIN_MARK.length, md.indexOf(END_MARK));
  for (const m of between.matchAll(/^\| (S\d) \| (.+?) \|/gm)) {
    themes[m[1]] = m[2].trim();
  }
  return themes;
}

/** Render the canonical marker block for the counted sessions. */
export function renderSummaryBlock(sessions, themes, today) {
  const rows = sessions.map((s) => {
    const theme = themes[s.id] ?? s.title ?? SESSION_THEMES[s.id] ?? '';
    const pct = s.total === 0 ? 0 : Math.round((s.done / s.total) * 100);
    return `| ${s.id} | ${theme} | ${s.done} / ${s.total} | ${pct}% |`;
  });
  const total = sessions.reduce((acc, s) => acc + s.total, 0);
  const done = sessions.reduce((acc, s) => acc + s.done, 0);
  const totalPct = total === 0 ? 0 : Math.round((done / total) * 100);
  return [
    BEGIN_MARK,
    `> Last updated: ${today} (auto-generated by \`pnpm gap:progress\` — the milestone ticks drive these numbers)`,
    '',
    '## Summary',
    '',
    '| Session | Theme | Milestones done | % |',
    '|---|---|---|---|',
    ...rows,
    `| **Total** | | **${done} / ${total}** | **${totalPct}%** |`,
    END_MARK,
  ].join('\n');
}

/**
 * Rewrite the file content between the markers. Throws (with a fix hint)
 * when the markers are missing so a restructured PROGRESS.md fails loudly
 * instead of silently drifting.
 *
 * @param {string} md
 * @param {string} [today] ISO date (injectable for tests)
 * @returns {string}
 */
export function rewriteProgress(md, today = new Date().toISOString().slice(0, 10)) {
  const begin = md.indexOf(BEGIN_MARK);
  const end = md.indexOf(END_MARK);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `gap-progress: markers missing or out of order — wrap the Summary block in\n  ${BEGIN_MARK}\n  …\n  ${END_MARK}`,
    );
  }
  const sessions = parseSessionCounts(md);
  if (sessions.length === 0) {
    throw new Error('gap-progress: no "### S<n>" session sections found — nothing to count');
  }
  const block = renderSummaryBlock(sessions, parseExistingThemes(md), today);
  return md.slice(0, begin) + block + md.slice(end + END_MARK.length);
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const fileArg = args.find((a) => !a.startsWith('--')) ?? DEFAULT_PATH;
  const original = readFileSync(fileArg, 'utf8');
  const updated = rewriteProgress(original);
  if (updated === original) {
    console.log(`gap-progress: already up to date (${fileArg})`);
    return 0;
  }
  if (check) {
    console.error(`gap-progress: STALE — ${fileArg} does not match its milestone ticks (run pnpm gap:progress)`);
    return 1;
  }
  writeFileSync(fileArg, updated);
  const sessions = parseSessionCounts(updated);
  const done = sessions.reduce((acc, s) => acc + s.done, 0);
  const total = sessions.reduce((acc, s) => acc + s.total, 0);
  console.log(`gap-progress: ${fileArg} updated — ${done}/${total} milestones done`);
  for (const s of sessions) console.log(`  ${s.id}: ${s.done}/${s.total}`);
  return 0;
}

// CLI only when invoked directly (the test imports the pure functions).
if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  process.exit(main());
}
