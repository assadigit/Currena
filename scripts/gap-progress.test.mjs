/**
 * gap-progress.test.mjs — unit tests for the S1-M3 progress tool
 * (node:test, zero dependencies — the repo's root has no vitest package).
 *
 * Fixture: tests/fixtures/gap-progress-sample.md (the existing
 * tests/fixtures pattern). Run: pnpm gap:progress:test
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  parseSessionCounts,
  parseExistingThemes,
  rewriteProgress,
  BEGIN_MARK,
  END_MARK,
} from './gap-progress.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fixture = readFileSync(join(here, '..', 'tests', 'fixtures', 'gap-progress-sample.md'), 'utf8');

test('parseSessionCounts counts only top-level M-milestone lines per section', () => {
  const counts = parseSessionCounts(fixture);
  assert.deepEqual(
    counts.map((s) => ({ id: s.id, done: s.done, total: s.total })),
    [
      { id: 'S1', done: 1, total: 2 },
      { id: 'S2', done: 0, total: 1 },
    ],
  );
});

test('parseExistingThemes preserves the human-written theme column', () => {
  const themes = parseExistingThemes(fixture);
  assert.equal(themes.S1, 'Foundation and trust');
  assert.equal(themes.S2, 'Foreign holdings of US Treasuries (priority feature)');
});

test('rewriteProgress regenerates the table, the totals and the date line', () => {
  const out = rewriteProgress(fixture, '2026-10-31');
  assert.ok(out.includes('> Last updated: 2026-10-31 (auto-generated by `pnpm gap:progress`'));
  assert.ok(out.includes('| S1 | Foundation and trust | 1 / 2 | 50% |'));
  assert.ok(out.includes('| S2 | Foreign holdings of US Treasuries (priority feature) | 0 / 1 | 0% |'));
  assert.ok(out.includes('| **Total** | | **1 / 3** | **33%** |'));
  // The milestone bodies and the gap-coverage items are untouched.
  assert.ok(out.includes('- [x] M1.1 First'));
  assert.ok(out.includes('- [x] G2 Treasury foreign-holder table (S2)'));
});

test('rewriteProgress is idempotent (same input twice → identical bytes)', () => {
  const once = rewriteProgress(fixture, '2026-10-31');
  const twice = rewriteProgress(once, '2026-10-31');
  assert.equal(twice, once);
});

test('rewriteProgress fails loudly when the markers are missing', () => {
  assert.throws(() => rewriteProgress('# no markers here\n'), /markers missing/);
});

test('rewriteProgress fails loudly when there are no session sections', () => {
  const noSections = `${BEGIN_MARK}\nold\n${END_MARK}\n\n## Milestones\n`;
  assert.throws(() => rewriteProgress(noSections), /no .*session/i);
});
