import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 900 } });
const errs: string[] = [];
page.on("pageerror", (e) => errs.push("PAGEERROR: " + String(e)));
page.on("console", (m) => { if (m.type() === "error") errs.push("CONSOLE: " + m.text()); });
console.log("goto...");
await page.goto("http://localhost:3100/tools/compound-wealth", { waitUntil: "domcontentloaded", timeout: 30000 });
console.log("loaded dcl, title:", await page.title());
await page.waitForTimeout(2500);
console.log("errors:", errs.length ? errs.join(" | ").slice(0, 500) : "none");
const donut = await page.$('[data-cw="share-donut"]');
console.log("donut present:", !!donut);
const cols = await page.$$('[data-cw="whatif-cols"]');
console.log("whatif cols:", cols.length);
const receipt = await page.$('#spending-receipt');
console.log("receipt present:", !!receipt);
await page.screenshot({ path: "docs/compound-tests/fb-debug-1.png" });
await browser.close();
