/**
 * Programme footer. Sticky to the bottom of the viewport on short pages,
 * pushed down naturally when the briefing runs long.
 *
 * S10: carries the honest provenance note — exactly which series are
 * live (EODHD) and which are modelled by the deterministic engine.
 * S11: the session line names the Continuity layer.
 * S13: the session line names the Watch layer.
 * S15: the session line closes the programme (the S14 digest included).
 */

import type { DeskProvenance } from "@/lib/gold/types";
import { fmtDayLabel } from "@/lib/gold/format";

interface DeskFooterProps {
  provenance?: DeskProvenance;
}

function provenanceSentence(p: DeskProvenance): string {
  const live = p.datasets.filter(
    (d) => d.mode === "live" || d.mode === "live-proxy"
  );
  const modelled = p.datasets.filter((d) => d.mode === "modelled");

  const parts: string[] = [];
  if (live.length > 0) {
    parts.push(
      `Live via EODHD as of ${fmtDayLabel(p.asOf)}: ${live
        .map((d) => `${d.label} (${d.source})`)
        .join(", ")}`
    );
  }
  if (modelled.length > 0) {
    parts.push(
      `modelled by the deterministic engine: ${modelled
        .map((d) => d.label)
        .join(", ")}`
    );
  }
  if (p.dataMode === "modelled" && p.fallbackReason) {
    parts.push(`fallback — ${p.fallbackReason}`);
  }
  return `${parts.join("; ")}.`;
}

export function DeskFooter({ provenance }: DeskFooterProps) {
  return (
    <footer className="mt-auto border-t border-border/70 bg-card">
      <div className="mx-auto flex max-w-7xl flex-col gap-3 px-4 py-6 text-xs text-muted-foreground sm:flex-row sm:items-center sm:justify-between sm:px-6 lg:px-8">
        <p>
          <span className="font-semibold text-foreground">AURUM Desk</span> ·
          Gold Intelligence &amp; Visual Explanation · Session 15 of 15 —
          programme complete (S8 Briefing + S9 Visuals + S10 live data + S11 track record + S12 scorecard + S13 owner watch rules + S14 digest)
        </p>
        <p className="max-w-xl leading-relaxed">
          {provenance
            ? `${provenanceSentence(provenance)} Figures are for demonstration and education — nothing here is investment advice.`
            : "All figures are generated by a deterministic market simulation for demonstration and education. Nothing here is investment advice."}
        </p>
      </div>
    </footer>
  );
}
